import assert from 'node:assert/strict';
import {selectionBounds,selectedView} from './dist/selection.js';
import {parseDecimal,zoomLog} from './dist/math.js';
const base={digits:40,cx:parseDecimal('-.7453',40).toString(),cy:parseDecimal('.1127',40).toString(),span:parseDecimal('.012',40).toString()};
const box=selectionBounds({x:600,y:400},{x:200,y:100},800,600);
assert.deepEqual(box,{x:200,y:100,width:400,height:300});
const n=selectedView(base,box,800,600);
assert.equal(n.cx,base.cx);
assert.equal(BigInt(n.cy),BigInt(base.cy)-BigInt(base.span)/16n);
assert.equal(BigInt(n.span),BigInt(base.span)/2n);
assert.equal(selectedView(base,{x:0,y:0,width:5,height:90},800,600),null);
assert.equal(selectedView(base,{x:0,y:0,width:800,height:600},800,600),null);
assert.deepEqual(selectionBounds({x:-50,y:700},{x:850,y:-50},800,600),{x:0,y:0,width:800,height:600});
const wide=selectedView(base,{x:100,y:100,width:400,height:40},800,600);
assert.equal(BigInt(wide.span),BigInt(base.span)/2n);
let deep={digits:390,cx:parseDecimal('-.743643887037151',390).toString(),cy:parseDecimal('.13182590420533',390).toString(),span:parseDecimal('1e-350',390).toString()};
for(let i=0;i<70;i++)deep=selectedView(deep,{x:200,y:150,width:400,height:300},800,600);
assert(zoomLog(deep)>370);assert(BigInt(deep.span)>0n);assert(deep.digits>390);
assert.equal(base.digits,40);console.log('Selection checks passed: reverse drag, clamp, aspect fit, tiny drags and arbitrary-precision zoom.');
